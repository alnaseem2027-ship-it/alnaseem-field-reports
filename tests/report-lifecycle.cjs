const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  page.on('dialog', (dialog) => dialog.accept());
  await page.goto('http://localhost:3001');
  await page.getByRole('button', { name: 'دخول النظام' }).click();
  await page.getByRole('button', { name: 'تقرير جديد' }).click();
  await page.getByLabel('اسم العميل', { exact: true }).fill('اختبار المسودة');
  await page.waitForTimeout(850);
  await page.reload();
  await page.getByRole('button', { name: 'دخول النظام' }).click();
  await page.getByRole('button', { name: 'متابعة المسودة' }).click();
  assert.equal(await page.getByLabel('اسم العميل', { exact: true }).inputValue(), 'اختبار المسودة');
  await page.getByRole('button', { name: 'حفظ التقرير', exact: true }).click();
  await page.getByRole('button', { name: 'تعديل', exact: true }).waitFor();
  await page.getByRole('button', { name: 'تعديل', exact: true }).click();
  await page.getByLabel('اسم العميل', { exact: true }).fill('اختبار التعديل');
  await page.getByRole('button', { name: 'حفظ التقرير', exact: true }).click();
  await page.getByRole('button', { name: 'حذف', exact: true }).click();
  await page.getByRole('button', { name: 'المحذوفات', exact: true }).click();
  await page.getByRole('button', { name: 'استرجاع', exact: true }).click();
  await page.getByRole('button', { name: 'التقارير', exact: true }).click();
  await page.getByRole('button', { name: 'سجل التعديلات', exact: true }).click();
  await page.getByRole('dialog', { name: 'سجل التعديلات' }).waitFor();
  const actions = await page.locator('.history-entry > strong').allTextContents();
  assert.deepEqual(actions, ['استرجاع', 'حذف', 'تعديل', 'إنشاء']);
  await page.getByRole('button', { name: 'عرض نسخة التقرير' }).first().click();
  await page.locator('.print-page').waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  console.log('PASS: draft after reload, save, edit, archive, restore, four history snapshots, mobile overflow.');
  await browser.close();
})().catch((error) => { console.error(error); process.exit(1); });
